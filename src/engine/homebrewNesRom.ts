/**
 * Generates a real, valid 40,976-byte iNES (.nes) binary ROM in memory containing:
 * - 16-byte iNES Header (NES\x1A, 2x16KB PRG-ROM, 1x8KB CHR-ROM, Mapper 0 NROM)
 * - 32KB 6502 Machine Code Program (initializes 2C02 PPU, loads palette & sprites into OAM,
 *   reads Controller 1 ($4016) & Controller 2 ($4017) in the 60Hz NMI interrupt, and moves P1/P2 commando sprites + fires projectiles!)
 * - 8KB 2-bitplanar CHR-ROM tile graphics
 */
export function buildBootable6502NesRomBytes(): Uint8Array {
  const HEADER_SIZE = 16;
  const PRG_SIZE = 32768; // 0x8000 - 0xFFFF
  const CHR_SIZE = 8192; // 8KB 8x8 tiles
  const rom = new Uint8Array(HEADER_SIZE + PRG_SIZE + CHR_SIZE);

  // 1. iNES 1.0 Header ("NES\x1A")
  rom[0] = 0x4e; // 'N'
  rom[1] = 0x45; // 'E'
  rom[2] = 0x53; // 'S'
  rom[3] = 0x1a; // DOS EOF
  rom[4] = 2; // 2 x 16KB PRG-ROM banks (32KB)
  rom[5] = 1; // 1 x 8KB CHR-ROM bank (8KB)
  rom[6] = 0x01; // Vertical Mirroring, Mapper 0
  rom[7] = 0x00;

  // 2. Populate CHR-ROM (offset 16 + 32768 = 32784) with 8x8 tiles
  const chrBase = HEADER_SIZE + PRG_SIZE;

  const writeTile = (tileIdx: number, rowsPlane0: number[], rowsPlane1: number[]) => {
    const offset = chrBase + tileIdx * 16;
    for (let r = 0; r < 8; r++) {
      rom[offset + r] = rowsPlane0[r] ?? 0;
      rom[offset + 8 + r] = rowsPlane1[r] ?? 0;
    }
  };

  // Tile 0x01: Commando Helmet/Torso Sprite
  writeTile(
    0x01,
    [0x3c, 0x7e, 0xff, 0xdb, 0xff, 0x7e, 0x3c, 0x66],
    [0x3c, 0x42, 0x81, 0x00, 0x7e, 0x3c, 0x24, 0x42]
  );

  // Tile 0x02: Spread Gun / Plasma Bullet Sprite
  writeTile(
    0x02,
    [0x00, 0x18, 0x3c, 0x7e, 0x7e, 0x3c, 0x18, 0x00],
    [0x00, 0x00, 0x18, 0x3c, 0x3c, 0x18, 0x00, 0x00]
  );

  // Tile 0x03: Steel Girder Background Block
  writeTile(
    0x03,
    [0xff, 0x81, 0xbd, 0xa5, 0xa5, 0xbd, 0x81, 0xff],
    [0xff, 0x7e, 0x42, 0x5a, 0x5a, 0x42, 0x7e, 0xff]
  );

  // 3. Populate 6502 Machine Code at $8000 (offset 16)
  const prgBase = HEADER_SIZE;
  let pc = 0;
  const emit = (...bytes: number[]) => {
    for (const b of bytes) {
      rom[prgBase + pc] = b & 0xff;
      pc += 1;
    }
  };

  // Zero-Page RAM Variables:
  // $0010: P1 X, $0011: P1 Y, $0012: P2 X, $0013: P2 Y
  // $0014: Bullet1 X, $0015: Bullet1 Y, $0016: Bullet2 X, $0017: Bullet2 Y
  // $0020: Controller 1 buttons, $0021: Controller 2 buttons

  // RESET Handler at $8000:
  emit(0x78, 0xd8); // SEI, CLD
  emit(0xa2, 0xff, 0x9a); // LDX #$FF, TXS
  emit(0xa9, 0x00); // LDA #$00
  emit(0x8d, 0x00, 0x20); // STA $2000 (PPUCTRL = 0)
  emit(0x8d, 0x01, 0x20); // STA $2001 (PPUMASK = 0)

  // Wait for 2 VBlanks
  // vwait1 ($800E): BIT $2002; BPL vwait1
  emit(0x2c, 0x02, 0x20, 0x10, 0xfb);
  // vwait2 ($8013): BIT $2002; BPL vwait2
  emit(0x2c, 0x02, 0x20, 0x10, 0xfb);

  // Initialize P1 ($10,$11) and P2 ($12,$13) positions
  emit(0xa9, 0x48, 0x85, 0x10); // LDA #$48; STA $10 (P1 X = 72)
  emit(0xa9, 0xb0, 0x85, 0x11); // LDA #$B0; STA $11 (P1 Y = 176)
  emit(0xa9, 0x98, 0x85, 0x12); // LDA #$98; STA $12 (P2 X = 152)
  emit(0xa9, 0xb0, 0x85, 0x13); // LDA #$B0; STA $13 (P2 Y = 176)
  emit(0xa9, 0x58, 0x85, 0x14); // Bullet1 X
  emit(0xa9, 0xb0, 0x85, 0x15); // Bullet1 Y
  emit(0xa9, 0xa8, 0x85, 0x16); // Bullet2 X
  emit(0xa9, 0xb0, 0x85, 0x17); // Bullet2 Y

  // Load NES Universal & Sprite Palettes at PPU $3F00
  emit(0x2c, 0x02, 0x20); // BIT $2002
  emit(0xa9, 0x3f, 0x8d, 0x06, 0x20); // LDA #$3F; STA $2006
  emit(0xa9, 0x00, 0x8d, 0x06, 0x20); // LDA #$00; STA $2006

  // Write 32 bytes of palette colors
  const paletteColors = [
    0x0f, 0x11, 0x21, 0x30, // BG0: Deep Black, Blue, Sky, White
    0x0f, 0x16, 0x27, 0x38, // BG1
    0x0f, 0x19, 0x29, 0x39, // BG2
    0x0f, 0x00, 0x10, 0x20, // BG3
    0x0f, 0x11, 0x21, 0x30, // SPR0 (Player 1 Blue Commando)
    0x0f, 0x06, 0x16, 0x30, // SPR1 (Player 2 Red Commando)
    0x0f, 0x28, 0x38, 0x30, // SPR2 (Spread Projectiles)
    0x0f, 0x1a, 0x2a, 0x30, // SPR3
  ];
  for (const col of paletteColors) {
    emit(0xa9, col, 0x8d, 0x07, 0x20); // LDA #col; STA $2007
  }

  // Draw a platform row in Nametable 0 at $22E0 (Row 23)
  emit(0x2c, 0x02, 0x20);
  emit(0xa9, 0x22, 0x8d, 0x06, 0x20);
  emit(0xa9, 0xe0, 0x8d, 0x06, 0x20);
  for (let c = 0; c < 64; c++) {
    emit(0xa9, 0x03, 0x8d, 0x07, 0x20); // Tile 0x03 Steel Girder
  }

  // Reset Scroll ($2005 = 0, 0) and Enable NMI + Sprites + Background
  emit(0xa9, 0x00, 0x8d, 0x05, 0x20, 0x8d, 0x05, 0x20);
  emit(0xa9, 0x80, 0x8d, 0x00, 0x20); // LDA #%10000000; STA $2000 (Enable NMI)
  emit(0xa9, 0x1e, 0x8d, 0x01, 0x20); // LDA #%00011110; STA $2001 (Show BG + Sprites)

  // Forever loop: JMP to current PC
  const loopAddr = 0x8000 + pc;
  emit(0x4c, loopAddr & 0xff, (loopAddr >> 8) & 0xff);

  // NMI Handler at $8300 (offset 16 + 0x0300)
  pc = 0x0300;
  // Save A, X, Y
  emit(0x48, 0x8a, 0x48, 0x98, 0x48);

  // Strobe Controllers $4016 = 1 then 0
  emit(0xa9, 0x01, 0x8d, 0x16, 0x40);
  emit(0xa9, 0x00, 0x8d, 0x16, 0x40);

  // Read 8 buttons from Controller 1 ($4016) into $20: A, B, Select, Start, Up, Down, Left, Right
  for (let b = 0; b < 8; b++) {
    emit(0xad, 0x16, 0x40); // LDA $4016
    emit(0x4a); // LSR A (bit 0 -> Carry)
    emit(0x26, 0x20); // ROL $20
  }

  // Read 8 buttons from Controller 2 ($4017) into $21
  for (let b = 0; b < 8; b++) {
    emit(0xad, 0x17, 0x40); // LDA $4017
    emit(0x4a); // LSR A
    emit(0x26, 0x21); // ROL $21
  }

  // Move Player 1 based on $20 bits (bit0=Right, bit1=Left, bit2=Down, bit3=Up)
  // Check Right (bit 0)
  emit(0xa5, 0x20, 0x29, 0x01, 0xf0, 0x04, 0xe6, 0x10, 0xe6, 0x10); // INC $10 x2
  // Check Left (bit 1)
  emit(0xa5, 0x20, 0x29, 0x02, 0xf0, 0x04, 0xc6, 0x10, 0xc6, 0x10); // DEC $10 x2
  // Check Down (bit 2)
  emit(0xa5, 0x20, 0x29, 0x04, 0xf0, 0x02, 0xe6, 0x11); // INC $11
  // Check Up (bit 3)
  emit(0xa5, 0x20, 0x29, 0x08, 0xf0, 0x02, 0xc6, 0x11); // DEC $11

  // Move Player 2 based on $21 bits
  emit(0xa5, 0x21, 0x29, 0x01, 0xf0, 0x04, 0xe6, 0x12, 0xe6, 0x12);
  emit(0xa5, 0x21, 0x29, 0x02, 0xf0, 0x04, 0xc6, 0x12, 0xc6, 0x12);
  emit(0xa5, 0x21, 0x29, 0x04, 0xf0, 0x02, 0xe6, 0x13);
  emit(0xa5, 0x21, 0x29, 0x08, 0xf0, 0x02, 0xc6, 0x13);

  // Advance Bullet 1 ($14) & Bullet 2 ($16) horizontally
  emit(0xe6, 0x14, 0xe6, 0x14, 0xe6, 0x14);
  emit(0xe6, 0x16, 0xe6, 0x16, 0xe6, 0x16);

  // Write OAM Sprites to $0200-$020F
  // Sprite 0 (P1): Y=$11, Tile=#$01, Attr=#$00, X=$10
  emit(0xa5, 0x11, 0x8d, 0x00, 0x02);
  emit(0xa9, 0x01, 0x8d, 0x01, 0x02);
  emit(0xa9, 0x00, 0x8d, 0x02, 0x02);
  emit(0xa5, 0x10, 0x8d, 0x03, 0x02);

  // Sprite 1 (P2): Y=$13, Tile=#$01, Attr=#$01 (Red Palette), X=$12
  emit(0xa5, 0x13, 0x8d, 0x04, 0x02);
  emit(0xa9, 0x01, 0x8d, 0x05, 0x02);
  emit(0xa9, 0x01, 0x8d, 0x06, 0x02);
  emit(0xa5, 0x12, 0x8d, 0x07, 0x02);

  // Sprite 2 (P1 Bullet): Y=$11, Tile=#$02, Attr=#$02, X=$14
  emit(0xa5, 0x11, 0x8d, 0x08, 0x02);
  emit(0xa9, 0x02, 0x8d, 0x09, 0x02);
  emit(0xa9, 0x02, 0x8d, 0x0a, 0x02);
  emit(0xa5, 0x14, 0x8d, 0x0b, 0x02);

  // Sprite 3 (P2 Bullet): Y=$13, Tile=#$02, Attr=#$02, X=$16
  emit(0xa5, 0x13, 0x8d, 0x0c, 0x02);
  emit(0xa9, 0x02, 0x8d, 0x0d, 0x02);
  emit(0xa9, 0x02, 0x8d, 0x0e, 0x02);
  emit(0xa5, 0x16, 0x8d, 0x0f, 0x02);

  // Trigger OAM DMA from $0200 ($4014 = #$02)
  emit(0xa9, 0x02, 0x8d, 0x14, 0x40);

  // Restore Y, X, A and RTI
  emit(0x68, 0xa8, 0x68, 0xaa, 0x68, 0x40);

  // 4. Write 6502 Interrupt Vectors at $FFFA-$FFFF (offset 16 + 0x7FFA)
  const vecOffset = prgBase + 0x7ffa;
  // NMI Vector -> $8300
  rom[vecOffset + 0] = 0x00;
  rom[vecOffset + 1] = 0x83;
  // RESET Vector -> $8000
  rom[vecOffset + 2] = 0x00;
  rom[vecOffset + 3] = 0x80;
  // IRQ/BRK Vector -> $8000
  rom[vecOffset + 4] = 0x00;
  rom[vecOffset + 5] = 0x80;

  return rom;
}
